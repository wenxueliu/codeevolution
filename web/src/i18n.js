export const locale = ref(readLocale())

function readLocale() {
  const stored = typeof window !== 'undefined' ? window.localStorage?.getItem(STORAGE_KEY) : null
  if (stored === 'en' || stored === 'zh') return stored
  // Keep the product default stable; users can opt into English with the
  // switch in the navigation bar, and the choice is persisted locally.
  return 'zh'
}

export function t(key, params = {}) {
  const source = (locale.value === 'en' ? en[key] : zh[key]) || key
  return source.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? `{${name}}`)
}

export function setLocale(next) {
  if (next !== 'zh' && next !== 'en') return
  locale.value = next
  if (typeof window !== 'undefined') {
    window.localStorage?.setItem(STORAGE_KEY, next)
    window.dispatchEvent(new CustomEvent(LOCALE_EVENT, { detail: next }))
    document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN'
  }
}

export function toggleLocale() {
  setLocale(locale.value === 'zh' ? 'en' : 'zh')
}

